/**
 * Derives every advertised count from the real data files and writes two
 * build artefacts:
 *
 *   src/data/siteCounts.js        — counts imported by the React app
 *   assets/data/ebooks-featured.json — 4-record homepage slice (~2 KB) so the
 *                                     homepage stops downloading the full
 *                                     1.1 MB ebooks.json to render 4 cards
 *
 * Run via `npm run build:data`. Counts were previously hand-maintained in five
 * files and had already drifted (the /courses title advertised 83 courses when
 * the catalog held 85).
 */

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const DATA_DIR = path.join(ROOT, "assets", "data");

function readJson(file, fallback) {
  try {
    return JSON.parse(fs.readFileSync(path.join(DATA_DIR, file), "utf8"));
  } catch {
    return fallback;
  }
}

const catalog = readJson("catalog.json", { courses: [] });
const ebooks = readJson("ebooks.json", { ebooks: [] });
const dictionary = readJson("dictionary.json", { terms: [], abbreviations: [] });
const papers = readJson("unmeb-essay-papers.json", []);
const instruments = readJson("medical-instruments.json", { categories: [] });

const paperList = Array.isArray(papers) ? papers : papers.papers || papers.exams || [];

const counts = {
  COURSE_COUNT: (catalog.courses || []).length,
  EBOOK_COUNT: (ebooks.ebooks || []).length,
  DICTIONARY_TERM_COUNT: (dictionary.terms || []).length,
  ABBREVIATION_COUNT: (dictionary.abbreviations || []).length,
  PAST_PAPER_COUNT: paperList.length,
  INSTRUMENT_COUNT: (instruments.categories || []).reduce(
    (sum, c) => sum + (c.items || []).length,
    0
  )
};

const banner = `// GENERATED by scripts/sync_site_counts.js — do not edit by hand.
// Run \`npm run build:data\` to refresh after changing assets/data/*.json.
`;

const body = Object.entries(counts)
  .map(([key, value]) => `export const ${key} = ${value};`)
  .join("\n");

const outFile = path.join(ROOT, "src", "data", "siteCounts.js");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${banner}\n${body}\n`);

// --- Homepage featured eBooks -------------------------------------------
// The homepage used only 4 records but fetched the whole file.
// Everything the homepage cards and EbookCover render — minus the `chapters`
// and `references` arrays, which are the entire weight of the file.
const FEATURED_FIELDS = [
  "slug",
  "title",
  "subtitle",
  "category",
  "coverImage",
  "updatedAt",
  "clinicalReviewer",
  "estimatedPages",
  "importedFromInfoBooks",
  "useEditorialCover"
];

const featured = (ebooks.ebooks || []).slice(0, 4).map((book) => {
  const slim = { chapterCount: (book.chapters || []).length };
  for (const field of FEATURED_FIELDS) {
    if (book[field] !== undefined) slim[field] = book[field];
  }
  return slim;
});

const featuredFile = path.join(DATA_DIR, "ebooks-featured.json");
fs.writeFileSync(featuredFile, JSON.stringify({ ebooks: featured }, null, 2));

console.log("site counts →", counts);
console.log(
  `ebooks-featured.json → ${featured.length} records, ${(
    fs.statSync(featuredFile).size / 1024
  ).toFixed(1)} KB`
);
